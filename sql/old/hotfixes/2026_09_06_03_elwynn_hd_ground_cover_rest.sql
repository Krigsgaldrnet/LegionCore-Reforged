-- HD ground cover for Elwynn, second pass
--
-- The first pass repointed the four heaviest ground effects, 4832 layers out of roughly 11000.
-- What was left showed in game as patches of the old, visibly pixelated tufts among the new ones.
--
-- These 34 records are the rest of Elwynn's own ground cover: every effect still painted on the
-- zone whose four doodad slots hold nothing but `elwgra*` and `elwflo*`. 2793 layers. Each slot is
-- swapped for the HD tuft closest in size to the one it replaces, and the record's own weights,
-- sound and density are kept, so the composition of each effect is unchanged.
--
--   elwgra01, 03, 05, 06, 08  ->  60000 grass_small      elwflo01, 03  ->  60004 flower_low
--   elwgra04, 07              ->  60001 grass_med        elwflo02      ->  60005 flower_tall
--   elwgra02                  ->  60002 grass_clump
--
-- Effect 512 is included this time. It sits on AeriePeaksScrubBrushBase, but its doodads are
-- Elwynn models: wherever that record is painted, Elwynn grass was already growing, so upgrading
-- it changes the definition and nothing else. The first pass left it out on the texture's name
-- alone, which was the wrong reading.
--
-- The 28 records still untouched mix in models from Duskwood, Westfall, Kalidar and the Wetlands.
-- Those stay as they are - repointing them would carry the change into the zones those models
-- belong to.
--
-- TableHash 2164840845 is GroundEffectTexture.
-- ==========================================================================================

